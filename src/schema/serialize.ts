import ts from 'typescript';
import type { LandoSchema } from './types.ts';
import { canonicalize } from './canonicalize.ts';
import { SchemaParseError } from './errors.ts';

/**
 * Emits the canonical TypeScript source for a `.lando/schema.ts` artifact.
 * The output is a single ESM module:
 *
 *   import type { LandoSchema } from 'lando';
 *
 *   export default {
 *     ...
 *   } satisfies LandoSchema;
 *
 * Output is byte-stable for any two structurally equal schemas — the
 * collection-ordering rules in `canonicalize` make sure of that. PRs
 * touching the artifact get clean diffs.
 *
 * Hand-editing the output is supported: the parser (`parseSchemaModule`)
 * goes through the TypeScript compiler so reformatting, comments, and
 * renamed identifiers all round-trip provided they don't break the
 * `export default <object> satisfies LandoSchema` skeleton.
 */
export function printSchemaModule(schema: LandoSchema): string {
  const canonical = canonicalize(schema);
  const body = printValue(canonical, 0);
  return [
    '// This file was generated by Lando. Hand-editable for fixups.',
    "// Do not remove the `satisfies LandoSchema` clause: it's load-bearing.",
    '',
    "import type { LandoSchema } from 'lando';",
    '',
    `export default ${body} satisfies LandoSchema;`,
    '',
  ].join('\n');
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const INDENT = '  ';

function printValue(value: unknown, depth: number): string {
  if (value === null) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) {
      throw new Error(`cannot serialize non-finite number: ${String(value)}`);
    }
    return String(value);
  }
  if (typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return printArray(value, depth);
  if (typeof value === 'object') return printObject(value as Record<string, unknown>, depth);
  throw new Error(`cannot serialize value of type ${typeof value}`);
}

function printArray(arr: unknown[], depth: number): string {
  if (arr.length === 0) return '[]';
  const childIndent = INDENT.repeat(depth + 1);
  const closeIndent = INDENT.repeat(depth);
  const lines = arr.map((v) => `${childIndent}${printValue(v, depth + 1)}`);
  return `[\n${lines.join(',\n')},\n${closeIndent}]`;
}

function printObject(obj: Record<string, unknown>, depth: number): string {
  const keys = Object.keys(obj).filter((k) => obj[k] !== undefined);
  if (keys.length === 0) return '{}';
  const childIndent = INDENT.repeat(depth + 1);
  const closeIndent = INDENT.repeat(depth);
  const lines = keys.map((k) => {
    const printedKey = IDENTIFIER.test(k) ? k : JSON.stringify(k);
    return `${childIndent}${printedKey}: ${printValue(obj[k], depth + 1)}`;
  });
  return `{\n${lines.join(',\n')},\n${closeIndent}}`;
}

// Parser ----------------------------------------------------------------

/**
 * Reads back a `.lando/schema.ts` source file. The parser walks the
 * TypeScript AST rather than `eval`-ing the source, so we don't execute
 * arbitrary user code at load time.
 *
 * The contract with hand-editors: the file's *default export* must be an
 * object literal (optionally followed by `satisfies LandoSchema` or
 * `as const`). Anything inside the literal must itself be a literal
 * (string, number, boolean, null, array, object). References, calls,
 * spreads, and template strings are rejected with `SchemaParseError`.
 */
export function parseSchemaModule(source: string): LandoSchema {
  const sf = ts.createSourceFile(
    '__lando_artifact.ts',
    source,
    ts.ScriptTarget.ESNext,
    /* setParentNodes */ true,
    ts.ScriptKind.TS,
  );

  let exported: ts.Expression | undefined;
  for (const stmt of sf.statements) {
    if (ts.isExportAssignment(stmt) && !stmt.isExportEquals) {
      exported = stmt.expression;
      break;
    }
  }
  if (exported === undefined) {
    throw new SchemaParseError(
      'artifact has no `export default` statement; expected `export default { … } satisfies LandoSchema`',
    );
  }

  const value = evaluateLiteral(unwrap(exported), sf);
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new SchemaParseError('default export is not an object literal');
  }
  return value as LandoSchema;
}

function unwrap(node: ts.Expression): ts.Expression {
  let cur: ts.Expression = node;
  while (true) {
    if (ts.isParenthesizedExpression(cur)) cur = cur.expression;
    else if (ts.isSatisfiesExpression(cur)) cur = cur.expression;
    else if (ts.isAsExpression(cur)) cur = cur.expression;
    else if (ts.isTypeAssertionExpression(cur)) cur = cur.expression;
    else return cur;
  }
}

function evaluateLiteral(node: ts.Expression, sf: ts.SourceFile): unknown {
  const inner = unwrap(node);
  switch (inner.kind) {
    case ts.SyntaxKind.NullKeyword:
      return null;
    case ts.SyntaxKind.TrueKeyword:
      return true;
    case ts.SyntaxKind.FalseKeyword:
      return false;
    case ts.SyntaxKind.StringLiteral:
    case ts.SyntaxKind.NoSubstitutionTemplateLiteral:
      return (inner as ts.StringLiteralLike).text;
    case ts.SyntaxKind.NumericLiteral:
      return Number((inner as ts.NumericLiteral).text);
    case ts.SyntaxKind.PrefixUnaryExpression: {
      const u = inner as ts.PrefixUnaryExpression;
      const operand = evaluateLiteral(u.operand, sf);
      if (typeof operand !== 'number') {
        throw fail(`unary operator on non-number`, u, sf);
      }
      if (u.operator === ts.SyntaxKind.MinusToken) return -operand;
      if (u.operator === ts.SyntaxKind.PlusToken) return +operand;
      throw fail(`unsupported unary operator`, u, sf);
    }
    case ts.SyntaxKind.ArrayLiteralExpression: {
      const arr = inner as ts.ArrayLiteralExpression;
      return arr.elements.map((el) => {
        if (ts.isSpreadElement(el)) {
          throw fail('spread elements are not allowed in artifact arrays', el, sf);
        }
        if (ts.isOmittedExpression(el)) {
          throw fail('elision (holes) is not allowed in artifact arrays', el, sf);
        }
        return evaluateLiteral(el, sf);
      });
    }
    case ts.SyntaxKind.ObjectLiteralExpression: {
      const obj = inner as ts.ObjectLiteralExpression;
      const out: Record<string, unknown> = {};
      for (const prop of obj.properties) {
        if (!ts.isPropertyAssignment(prop)) {
          throw fail(
            `unsupported property kind ${ts.SyntaxKind[prop.kind]}; only \`key: value\` allowed`,
            prop,
            sf,
          );
        }
        const key = readKey(prop.name, sf);
        out[key] = evaluateLiteral(prop.initializer, sf);
      }
      return out;
    }
    default:
      throw fail(`unsupported expression kind ${ts.SyntaxKind[inner.kind]}`, inner, sf);
  }
}

function readKey(name: ts.PropertyName, sf: ts.SourceFile): string {
  if (ts.isIdentifier(name)) return name.text;
  if (ts.isStringLiteral(name) || ts.isNoSubstitutionTemplateLiteral(name)) return name.text;
  if (ts.isNumericLiteral(name)) return name.text;
  throw fail(`unsupported key kind ${ts.SyntaxKind[name.kind]}`, name, sf);
}

function fail(reason: string, node: ts.Node, sf: ts.SourceFile): SchemaParseError {
  const { line, character } = sf.getLineAndCharacterOfPosition(node.getStart(sf));
  return new SchemaParseError(`${reason} (at line ${line + 1}, col ${character + 1})`);
}
